from fastapi import APIRouter, HTTPException, status

# 1. ИМПОРТ ЗАВИСИМОСТЕЙ (Инструменты контроля и авто-проверок)
from dependencies.db import DBSession  # Открывает и закрывает сессию к базе данных
from dependencies.get_todo import TodoOr404  # 🔥 ПАТТЕРН "Умный б bodyguard". Если Todo нет в базе — сразу выкинет 404, экономя строки кода в функциях ниже.

# 2. ИМПОРТ СХЕМ И CRUD (Данные и Логика)
from schemas import TagBase
from CRUD.teg_crud import (
    list_tags_db,
    add_tag_to_todo_db,
    delete_tag_from_todo_db,
    delete_global_tag_db
)

# 3. НАСТРОЙКА РОУТЕРА
router = APIRouter(
    prefix="/tags",  # Все URL в этом файле автоматически стартуют с префикса /tags
    tags=["Tags"]    # Группирует эндпоинты в красивую вкладку "Tags" в Swagger (/docs)
)


# =====================================================================
# ТРАФАРЕТ №1: Обычный GET-запрос (Получение плоского списка)
# ДЛЯ ЧЕГО: Выгрузить справочник элементов (все категории, все теги, все страны).
# =====================================================================
@router.get("/", summary="Получить все элементы")
def get_all_items(session: DBSession):
    """
    Классический эндпоинт для вывода всех записей без фильтрации.
    """
    # Шаг A: Запрашиваем данные из базы через CRUD
    items_from_db = list_tags_db(session)

    # Шаг B: Превращаем объекты базы в простые словари через генератор списков (list comprehension)
    return [{"id": item.id, "name": item.name} for item in items_from_db]


# =====================================================================
# ТРАФАРЕТ №2: GET-запрос по ID с кастомной зависимостью (Фильтр и Связи)
# ДЛЯ ЧЕГО: Посмотреть карточку объекта и все сущности, которые к нему привязаны.
# =====================================================================
@router.get("/todos/{todo_id}", summary="Получить детальную инфу по ID")
def get_item_by_id(todo: TodoOr404):
    """
    Благодаря зависимости TodoOr404, мы пишем логику ТОЛЬКО для успешного сценария.
    Если id в пути (/todos/999) не существует, FastAPI прервет запрос на входе.
    """
    # Сразу собираем ответ. Зависимость уже загрузила все связи благодаря lazy="selectin" в модели.
    return {
        "id": todo.id,
        "title": todo.title,
        "description": todo.description,
        "completed": todo.completed,
        "deadline": todo.deadline,
        "user_id": todo.user_id,
        # Разбираем вложенный список связей Many-to-Many в красивый JSON-массив
        "tags": [{"id": tag.id, "name": tag.name} for tag in todo.tags]
    }


# =====================================================================
# ТРАФАРЕТ №3: POST-запрос (Создание / Привязка данных в Many-to-Many)
# ДЛЯ ЧЕГО: Создать новый тег и ОДНОВРЕМЕННО прикрепить его к существующей задаче.
# =====================================================================
@router.post(
    "/todos/{todo_id}",
    status_code=status.HTTP_201_CREATED, # Для POST-запросов хорошим тоном считается возвращать 201 Created
    summary="Создать или привязать данные"
)
def create_or_link_item(
        body: TagBase,       # FastAPI валидирует JSON от клиента по схеме TagBase (проверяет строку)
        session: DBSession,  # Открывает доступ к транзакциям базы
        todo: TodoOr404      # Гарантирует, что мы не пытаемся привязать тег к "воздуху"
):
    # Шаг A: Передаем всё в CRUD. Он создаст тег (или найдет существующий) и обновит таблицу-мост `todo_tag`
    updated_todo = add_tag_to_todo_db(session, todo, body)

    # Шаг B: Возвращаем клиенту результат, чтобы он видел актуальное состояние задачи и её тегов
    return {
        "id": updated_todo.id,
        "title": updated_todo.title,
        "tags": [{"id": tag.id, "name": tag.name} for tag in updated_todo.tags]
    }


# =====================================================================
# ТРАФАРЕТ №4: DELETE-запрос для Разрыва Связи (Many-to-Many)
# ДЛЯ ЧЕГО: Отвязать тег от задачи, но ОСТАВИТЬ сам тег в базе данных для других задач.
# =====================================================================
@router.delete("/todos/{todo_id}/{tag_id}", summary="Отвязать один элемент от другого")
def disconnect_items(tag_id: int, session: DBSession, todo: TodoOr404):
    """
    Шаблон для удаления строки из промежуточной таблицы-моста.
    Оба объекта (Задача и Тег) выживают, стирается только связь между ними.
    """
    # Шаг A: Валидация «на месте». Проверяем, а была ли вообще такая связь у этой задачи?
    # any() пробегает по списку тегов задачи и возвращает True, если наткнется на нужный tag_id
    link_exists = any(tag.id == tag_id for tag in todo.tags)

    if not link_exists:
        # Если связи не было — прерываем выполнение и отдаем 404
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={"message": "Связь между объектами не найдена"}
        )

    # Шаг B: Если связь подтверждена — вызываем CRUD для её удаления из таблицы-моста
    updated_todo = delete_tag_from_todo_db(session, todo, tag_id)

    # Шаг C: Отдаем обновленный объект задачи, где этого тега уже нет
    return {
        "message": "Связь успешно удалена",
        "id": updated_todo.id,
        "tags": [{"id": tag.id, "name": tag.name} for tag in updated_todo.tags]
    }


# =====================================================================
# ТРАФАРЕТ №5: Обычный DELETE-запрос (Полное жесткое удаление записи из БД)
# ДЛЯ ЧЕГО: Стереть элемент из глобального справочника насовсем.
# =====================================================================
@router.delete("/{tag_id}", summary="Удалить элемент из базы насовсем")
def delete_item_permanently(tag_id: int, session: DBSession):
    """
    Шаблон для полного уничтожения сущности.
    Благодаря ondelete="CASCADE" на нашей промежуточной таблице, при удалении тега
    база данных САМА зайдет в таблицу-мост и вычистит оттуда все упоминания этого тега.
    """
    # Шаг A: Вызываем CRUD функцию, которая удаляет запись и возвращает True (успех) или False (не нашел)
    success = delete_global_tag_db(session, tag_id)

    # Шаг B: Обрабатываем случай, если тега с таким ID и так не было в системе
    if not success:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={"message": "Элемент не найден в базе данных"}
        )

    # Шаг C: Если всё ок — возвращаем текстовое подтверждение
    return {"message": f"Элемент с ID {tag_id} успешно стерт из системы"}