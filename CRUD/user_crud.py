from sqlalchemy import select
from sqlalchemy.orm import selectinload, Session
from models import User, Profile, Todo
from schemas import UserCreate, UserUpdate


# =====================================================================
# 1. СЦЕНАРИЙ: СОЗДАНИЕ СВЯЗАННЫХ ЗАПИСЕЙ (Связь 1:1 "User" и "Profile")
# =====================================================================
def create_user_db(session: Session, body: UserCreate) -> User:
    """
    Создает пользователя И сразу генерирует для него пустую строку профиля.
    Шаблон для: Кейсов, когда при регистрации сущности (User, Company, Shop)
    нужно автоматически создать её дочернюю сущность (Profile, Settings, Balance).
    """
    # Шаг 1: Создаем объект главного класса (User) с данными из Pydantic-схемы
    user = User(username=body.username)
    session.add(user)

    # Шаг 2: КРИТИЧЕСКИЙ МОМЕНТ!
    # Вызываем flush(). Он отправляет запрос в БД прямо сейчас, не закрывая транзакцию.
    # Это нужно ТОЛЬКО для того, чтобы база сгенерировала ID для нового пользователя (user.id).
    # Без flush() поле user.id было бы равно None, и мы не смогли бы привязать профиль.
    session.flush()

    # Шаг 3: Создаем дочерний объект (Profile), используя сгенерированный user.id
    profile = Profile(user_id=user.id)
    session.add(profile)

    # Шаг 4: Фиксируем изменения в базе. Если что-то пойдет не так на Шаге 3,
    # благодаря единой транзакции откатится и Шаг 1 (юзер без профиля не создастся).
    session.commit()

    # Шаг 5: Перечитываем объект из базы, чтобы наполнить его актуальными данными
    session.refresh(user)
    return user


# =====================================================================
# 2. СЦЕНАРИЙ: ПОЛУЧЕНИЕ ОДНОЙ ЗАПИСИ С ЖАДНОЙ ЗАГРУЗКОЙ (Жёсткий отбор)
# =====================================================================
def get_user_by_id_db(session: Session, user_id: int) -> User | None:
    """
    Находит одну запись по ID и сразу подтягивает все связанные таблицы.
    Шаблон для: Получения детальной информации (Карточка товара с отзывами,
    Профиль юзера с его заказами).
    """
    # Шаг 1: Пишем базовый SELECT-запрос к таблице
    stmt = select(User).where(User.id == user_id).options(
        # Шаг 2: Используем selectinload для борьбы с проблемой "N+1 запросов".
        # Без этого при попытке прочитать user.todos в роутере, SQLAlchemy делала бы
        # скрытый ленивый запрос в БД для каждого пользователя.
        # selectinload делает ОДИН дополнительный эффективный запрос через SQL JOIN/IN.
        selectinload(User.todos),
        selectinload(User.profile)
    )

    # Шаг 3: Выполняем запрос.
    # .scalars() преобразует сырые строки SQL в объекты Python (модели User).
    # .one_or_none() возвращает ОДИН объект, если нашли, или None, если ID нет в базе.
    return session.execute(stmt).scalars().one_or_none()


# =====================================================================
# 3. СЦЕНАРИЙ: ПОЛУЧЕНИЕ СПИСКА ЗАПИСЕЙ С ГЛУБОКОЙ СВЯЗЬЮ (Вложенная загрузка)
# =====================================================================
def get_list_users(session: Session) -> list[User]:
    """
    Возвращает список всех сущностей, сортируя их и загружая глубокие связи.
    Шаблон для: Вывода таблиц, каталогов, ленты новостей с авторами и тегами.
    """
    stmt = (
        select(User)
        .options(
            # Подгружаем профиль (связь первого уровня)
            selectinload(User.profile),
            # Подгружаем задачи (связь первого уровня) И ПАРОВОЗИКОМ (.selectinload)
            # загружаем теги, которые привязаны к этим задачам (связь второго уровня).
            selectinload(User.todos).selectinload(Todo.tags)
        )
        # Сортировка по алфавиту (.asc() - от А до Я, .desc() - от Я до А)
        .order_by(User.username.asc())
    )

    result = session.execute(stmt)
    # .all() превращает результат в стандартный список Python [User, User, User]
    return list(result.scalars().all())


# =====================================================================
# 4. СЦЕНАРИЙ: УДАЛЕНИЕ СУЩНОСТИ С ВОЗВРАТОМ ОБНОВЛЕННОГО СПИСКА
# =====================================================================
def delete_user_db(session: Session, user_id: int) -> list[User] | None:
    """
    Удаляет объект из БД. Если объекта нет, не паникует, а сообщает роутеру.
    Шаблон для: Любого удаления по ID.
    """
    # Шаг 1: Сначала ищем то, что хотим удалить
    stmt = select(User).where(User.id == user_id)
    user = session.execute(stmt).scalar_one_or_none()

    # Шаг 2: Защита. Если записи в базе нет, возвращаем None.
    # Ошибку 404 кинет роутер, CRUD-функция не должна знать про HTTP-статусы.
    if not user:
        return None

        # Шаг 3: Говорим сессии пометить объект на удаление и фиксируем в БД
    session.delete(user)
    session.commit()

    # Шаг 4: Удобный паттерн для SPA-приложений (фронтенда):
    # Вместо пустого ответа возвращаем свежий список пользователей, чтобы фронт сразу обновил экран.
    return get_list_users(session)


# =====================================================================
# 5. СЦЕНАРИЙ: ОБНОВЛЕНИЕ ДАННЫХ ЗАПИСИ (Использование готовых кирпичиков)
# =====================================================================
def update_user_db(session: Session, user_id: int, body: UserUpdate) -> User | None:
    """
    Модифицирует существующую запись.
    Шаблон для: Редактирования настроек, изменения статусов заказов, смены паролей.
    """
    # Шаг 1: Переиспользуем уже написанную нами функцию поиска (get_user_by_id_db).
    # Зачем писать select заново, если он уже готов выше? К тому же он сразу подгрузит связи.
    user = get_user_by_id_db(session, user_id)

    # Шаг 2: Если пользователь нашелся — меняем поля данными из Pydantic-схемы
    if user:
        user.username = body.username  # Перезаписываем старое значение новым

        # Шаг 3: Сохраняем изменения в БД
        session.commit()
        session.refresh(user)
        return user

    # Шаг 4: Если не нашелся — возвращаем None (роутер отдаст 404)
    return None