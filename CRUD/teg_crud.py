from sqlalchemy import select, delete
from sqlalchemy.orm import Session
from models import Todo, Tag, todo_tag
from schemas import TagBase


# =====================================================================
# 1. СЦЕНАРИЙ: READ — ПОЛУЧЕНИЕ ГЛОБАЛЬНОГО СПРАВОЧНИКА (GET)
# =====================================================================
def list_tags_db(session: Session) -> list[Tag]:
    """
    Выгружает абсолютно все теги, существующие в системе.
    Шаблон для: Заполнения выпадающих списков (селектов) на фронтенде, 
    вывода облака тегов или глобальных категорий.
    """
    stmt = select(Tag)
    result = session.execute(stmt)
    return list(result.scalars().all())


# =====================================================================
# 2. СЦЕНАРИЙ: CREATE — УМНОЕ ДОБАВЛЕНИЕ СУЩНОСТИ И СВЯЗИ
# =====================================================================
def add_tag_to_todo_db(session: Session, todo: Todo, tag_data: TagBase) -> Todo:
    """
    Добавляет тег к задаче, избегая дублирования как самих тегов, так и связей.
    Шаблон для: Добавления навыков к резюме, жанров к фильму, тегов к статье.
    """
    # Шаг 1: Защита от дублирования сущностей.
    # Проверяем, есть ли уже в базе тег с точно таким же именем (например, "Работа").
    stmt = select(Tag).where(Tag.name == tag_data.name)
    tag = session.execute(stmt).scalar_one_or_none()

    # Шаг 2: Если такого тега еще нет — создаем его в единственном экземпляре
    if not tag:
        tag = Tag(name=tag_data.name)
        session.add(tag)
        # flush() отправляет тег в БД, чтобы база сгенерировала ему уникальный tag.id.
        # Но транзакцию мы не закрываем, так как работа еще не закончена.
        session.flush()

        # Шаг 3: Защита от дублирования связей в таблице-мосте.
    # Проверяем, не привязан ли этот тег к нашей задаче прямо сейчас.
    if tag not in todo.tags:
        # Если связи нет — просто добавляем объект тега в ORM-список задачи.
        # SQLAlchemy сама поймет, что нужно вставить строчку в таблицу `todo_tag`.
        todo.tags.append(tag)

    # Шаг 4: Синхронизируем всё с базой данных одной неделимой транзакцией.
    session.commit()
    session.refresh(todo)

    return todo


# =====================================================================
# 3. СЦЕНАРИЙ: DELETE — РАЗРЫВ СВЯЗИ (УДАЛЕНИЕ ИЗ ТАБЛИЦЫ-МОСТА)
# =====================================================================
def delete_tag_from_todo_db(session: Session, todo: Todo, tag_id: int) -> Todo:
    """
    Удаляет СВЯЗЬ между задачей и тегом. При этом сама задача и сам тег остаются в базе.
    Шаблон для: Операции "убрать тег из этой задачи" или "удалить товар из корзины".
    """
    # Шаг 1: Конструируем прямой низкоуровневый DELETE-запрос к таблице-мосту `todo_tag`.
    # Мы целимся строго в пересечение ID нашей задачи и ID удаляемого тега.
    stmt = (
        delete(todo_tag)
        .where(todo_tag.c.todo_id == todo.id)
        .where(todo_tag.c.tag_id == tag_id)
    )
    session.execute(stmt)

    # Шаг 2: Фиксируем удаление строки-связи в базе данных
    session.commit()

    # Шаг 3: КРИТИЧЕСКИ ВАЖНО ДЛЯ MANY-TO-MANY!
    # Вызываем expire_all(), чтобы принудительно стереть кэш объектов в памяти Python.
    # Если этого не сделать, SQLAlchemy вернет объект `todo` со старым (уже удаленным) 
    # списком тегов, потому что она возьмет его из своей памяти, а не из реальной базы.
    session.expire_all()

    # Шаг 4: Перечитываем чистую задачу из базы данных, теперь она уже без этого тега
    session.refresh(todo)

    return todo


# =====================================================================
# 4. СЦЕНАРИЙ: DELETE — ПОЛНОЕ УНИЧТОЖЕНИЕ ГЛОБАЛЬНОЙ СУЩНОСТИ
# =====================================================================
def delete_global_tag_db(session: Session, tag_id: int) -> bool:
    """
    Полностью удаляет тег из таблицы `tags` по его глобальному ID.
    Шаблон для: Панели администратора, когда нужно удалить категорию или тег целиком из системы.
    """
    # Шаг 1: Пробуем найти тег в базе по его ID
    tag = session.get(Tag, tag_id)

    if tag:
        # Шаг 2: Если нашли — удаляем.
        # Благодаря каскадному удалению в БД (ondelete="CASCADE"), база данных 
        # автоматически вычистит все упоминания этого тега из таблицы-моста `todo_tag`.
        session.delete(tag)
        session.commit()
        return True  # Сигнал роутеру, что всё прошло успешно (отдаем 200)

    return False  # Сигнал роутеру, что тег не найден (отдаем 404)