from datetime import datetime
from pydantic import BaseModel, Field

# =====================================================================
# 1. СХЕМЫ ДЛЯ ПОЛЬЗОВАТЕЛЕЙ (User)
# =====================================================================
class UserBase(BaseModel):
    """
    Базовая схема. Содержит поля, которые есть ВСЕГДА и везде.
    От нее наследуются остальные схемы пользователей, чтобы не дублировать код.
    """
    username: str = Field(max_length=320, description="Уникальное имя пользователя")


class UserCreate(UserBase):
    """
    Схема для POST-запроса (Регистрация).
    Сюда добавляются поля, которые нужны ТОЛЬКО при создании.
    Шаблон для: password: str, email: EmailStr и т.д.
    """
    pass


class UserUpdate(UserBase):
    """
    Схема для PUT/PATCH-запросов (Редактирование).
    Обычно полностью совпадает с базовой или делает поля необязательными.
    """
    pass


class UserDelete(UserBase):
    """
    Редко используется. Чаще всего для удаления достаточно ID в URL-пути,
    но если для удаления нужен текстовый запрос, можно использовать её.
    """
    pass


# =====================================================================
# 2. СХЕМЫ ДЛЯ ПРОФИЛЯ (Profile)
# =====================================================================
class ProfileUpdate(BaseModel):
    """
    Схема-универсал для Профиля.
    В URL у нас уже есть /users/{user_id}/profile, поэтому Pydantic-тело
    не должно требовать никаких ID. Мы передаем только то, что настраивает юзер.
    """
    # default=None делает поле необязательным (клиент может прислать пустой JSON {})
    bio: str | None = Field(default=None, max_length=500, description="Информация о себе")


# =====================================================================
# 3. СХЕМЫ ДЛЯ ТЕГОВ (Tag)
# =====================================================================
class TagBase(BaseModel):
    name: str = Field(max_length=255, description="Название тега (например: Работа, Семья)")


class TagRead(TagBase):
    """
    Схема для возврата тега клиенту (Response JSON).
    При чтении из базы данных у тега появляется физический ID,
    который мы обязаны показать фронтенду.
    """
    id: int

    # Для SQLAlchemy моделей в Pydantic v2 этот режим (from_attributes=True)
    # часто включают в Config, чтобы Pydantic умел читать данные прямо из ORM-объектов.
    class Config:
        from_attributes = True


# =====================================================================
# 4. СХЕМЫ ДЛЯ ЗАДАЧ (Todo) — Базовый CRUD
# =====================================================================
class TodoBase(BaseModel):
    """
    Основа для любой задачи. Проверяет минимальную и максимальную длину строк,
    а также валидирует, что дата дедлайна пришла в правильном формате ISO.
    """
    title: str = Field(min_length=3, max_length=255)
    description: str | None = Field(default=None, max_length=1024)
    completed: bool = Field(default=False)
    deadline: datetime


class TodoCreate(TodoBase):
    """
    Запрос на создание задачи.
    Обязательно требует указать user_id, чтобы связать задачу с конкретным создателем.
    """
    user_id: int


class TodoUpdate(TodoBase):
    """
    Используется для PUT-запроса (Полное обновление задачи).
    Требует передать ВСЕ поля из TodoBase заново.
    """
    pass


class TodoRead(TodoBase):
    """
    Схема для базового ответа (GET /todos/{id}).
    Возвращает все поля задачи, включая её сгенерированный id и id автора.
    """
    id: int
    user_id: int


class TodoModify(BaseModel):
    """
    Схема для PATCH-запроса (Частичное обновление).
    КРИТИЧЕСКИЙ ШАБЛОН: Обрати внимание, здесь ВСЕ поля имеют `default=None` или `| None = None`.
    Это нужно для того, чтобы клиент мог обновить ТОЛЬКО одно поле, например: {"completed": true}.
    Все остальные поля останутся нетронутыми.
    """
    title: str | None = Field(default=None, min_length=3, max_length=255)
    description: str | None = Field(default=None, max_length=1024)
    completed: bool | None = None
    deadline: datetime | None = None


# =====================================================================
# 5. СХЕМЫ ДЛЯ СЛОЖНЫХ СВЯЗОК (Задачи + Теги) — Продвинутый уровень
# =====================================================================
class TodoCreateTag(TodoCreate):
    """
    Продвинутый POST: позволяет создать задачу и СРАЗУ прикрепить к ней
    список тегов в одном запросе.
    """
    tags: list[TagBase]


class TodoWithTagsRead(TodoRead):
    """
    Продвинутый GET (Вложенный маппинг).
    Используется в роутерах, когда нужно выдать задачу, а внутри нее — список тегов.
    Вложенность list[TagRead] автоматически сериализует объекты тегов в JSON-массив.
    """
    tags: list[TagRead] = []